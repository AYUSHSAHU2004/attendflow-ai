"""The Autonomy Table: every action the system can take, who may take it, and what stops it.

This registry is the single source of truth. The app's Autonomy tab, `GET /api/autonomy`
and the README section "Autonomy and guardrails" are all generated from it, and tests keep
it honest (tests/test_autonomy.py):

- every audit action any code path can write is listed here (a static scan of the code,
  plus a check on every audit row the whole test suite writes);
- every row that needs a person names tests that prove the refusal without that person;
- every autonomous row is produced, with its listed actor, by the end-to-end story;
- the README copy is regenerated by `attendflow-autonomy --write-readme` and must match.

Actor types: `code` (the deterministic rule engine and fix writer), `llm_agent` (the model,
validated by code), `system` (the scheduler and the no-reply ladder), `device` (a punch
terminal) and `human` (a worker, a supervisor or the payroll admin). `audit_actors` are the
values the matching rows carry in `audit_log.actor`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

ActorType = Literal["code", "llm_agent", "system", "device", "human"]
Approval = Literal["none", "supervisor", "payroll_admin", "supervisor_or_payroll_admin"]
Reversible = Literal["yes_undo", "no", "not_applicable"]
Kind = Literal["allowed", "never"]

ACTOR_TYPE_LABELS: dict[str, str] = {
    "code": "Code",
    "llm_agent": "LLM agent",
    "system": "System",
    "device": "Device",
    "human": "Human",
}
APPROVAL_LABELS: dict[str, str] = {
    "none": "None",
    "supervisor": "Supervisor",
    "payroll_admin": "Payroll admin",
    "supervisor_or_payroll_admin": "Supervisor (payroll admin once escalated)",
}
REVERSIBLE_LABELS: dict[str, str] = {
    "yes_undo": "Yes, with undo",
    "no": "No",
    "not_applicable": "Not applicable",
}
# audit_log.actor values that act without a person.
AUTONOMOUS_AUDIT_ACTORS = ("system", "agent", "device")


@dataclass(frozen=True)
class Capability:
    key: str
    title: str
    actor_type: ActorType
    performed_by: str
    approval: Approval
    reversible: Reversible
    guardrail: str
    kind: Kind = "allowed"
    audit_actions: tuple[str, ...] = ()
    audit_actors: tuple[str, ...] = ()
    # Tests that prove the approval (refusal without the right person) or the "never" limit.
    proof_tests: tuple[str, ...] = ()

    @property
    def autonomous(self) -> bool:
        return self.kind == "allowed" and self.actor_type != "human" and self.approval == "none"


