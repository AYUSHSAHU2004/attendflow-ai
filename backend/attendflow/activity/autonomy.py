def allowed() -> tuple[Capability, ...]:
    return tuple(c for c in CAPABILITIES if c.kind == "allowed")


def registered_actions() -> set[str]:
    return {a for c in allowed() for a in c.audit_actions}


def capability_for(action: str, actor: str) -> Capability | None:
    """The row that covers this audit (action, actor) pair, if any."""
    for c in allowed():
        if action in c.audit_actions and actor in c.audit_actors:
            return c
    return None


# ---------------------------------------------------------------- README rendering

README_START = "<!-- autonomy-table:start (generated by attendflow-autonomy; do not edit) -->"
README_END = "<!-- autonomy-table:end -->"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def as_markdown() -> str:
    lines = [
        "Generated from `backend/attendflow/activity/autonomy.py` by "
        "`python -m uv run attendflow-autonomy --write-readme`. A test fails if this copy is "
        "out of date, if any code path writes an audit action missing from the registry, or "
        "if a row's named tests do not exist.",
        "",
        "| Action | Actor | Done by | Approval needed | Reversible | Guardrail |",
        "|---|---|---|---|---|---|",
    ]
    for c in allowed():
        lines.append(
            f"| {_cell(c.title)} | {ACTOR_TYPE_LABELS[c.actor_type]} | {_cell(c.performed_by)} "
            f"| {APPROVAL_LABELS[c.approval]} | {REVERSIBLE_LABELS[c.reversible]} "
            f"| {_cell(c.guardrail)} |"
        )
    lines += ["", "**Never allowed**", "", "| Never | Who | Guardrail |", "|---|---|---|"]
    for c in CAPABILITIES:
        if c.kind == "never":
            lines.append(f"| {_cell(c.title)} | {_cell(c.performed_by)} | {_cell(c.guardrail)} |")
    return "\n".join(lines) + "\n"


def render_readme(readme: str) -> str:
    """The README with the generated block replaced (it must already have the markers)."""
    start = readme.index(README_START) + len(README_START)
    end = readme.index(README_END)
    return readme[:start] + "\n" + as_markdown() + readme[end:]
